// Deploy engine/ as a standalone preview Worker (satsang-engine-preview) on engine.tantrafiles.xyz.
// Touches nothing else: one new Worker script + one Worker custom domain (Cloudflare creates its own DNS record).
// Auth: the Hark gateway (or CLOUDFLARE_API_TOKEN) supplies the credential for api.cloudflare.com.
// usage: node tools/deploy-preview.mjs [--dry]
import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..')
const ACCOUNT = '954612afb5a97bb15dddcdc70176813d', ZONE = '4314ed02dc4c6f4cc1f6bf7638aa3a10'
const NAME = 'satsang-engine-preview', HOST = 'engine.tantrafiles.xyz'
const FILES = ['demo/index.html', 'compile.mjs', 'grammar.json', 'player/engine.js', 'player/player.js', 'player/player.css',
  ...fs.readdirSync(path.join(ROOT, 'practices')).map(f => 'practices/' + f), 'GRAMMAR.md', 'schema/practice-v2.json', 'schema/timeline.json']
const TYPES = { '.html': 'text/html; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.md': 'text/markdown; charset=utf-8' }
const assets = Object.fromEntries(FILES.map(f => ['/' + f, [TYPES[path.extname(f)], fs.readFileSync(path.join(ROOT, f), 'utf8')]]))
const worker = `// generated by engine/tools/deploy-preview.mjs: static preview of the Satsang practice engine
const A = ${JSON.stringify(assets)};
export default { async fetch(req) {
  const u = new URL(req.url);
  let p = u.pathname;
  if (p === '/' || p === '/demo') return Response.redirect(u.origin + '/demo/' + u.search, 302);
  if (p.endsWith('/')) p += 'index.html';
  const a = A[p];
  if (!a) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
  return new Response(a[1], { headers: { 'content-type': a[0], 'cache-control': 'public, max-age=300', 'x-robots-tag': 'noindex', 'x-content-type-options': 'nosniff', 'referrer-policy': 'strict-origin-when-cross-origin' } });
} };
`
fs.mkdirSync('/tmp/satsang-engine-worker', { recursive: true })
fs.writeFileSync('/tmp/satsang-engine-worker/worker.js', worker)
console.log(`worker.js ${(worker.length / 1024).toFixed(1)} KB, ${FILES.length} files`)
if (process.argv.includes('--dry')) process.exit(0)
// curl, not fetch: the credential gateway sits on curl's proxy path
import { execFileSync } from 'node:child_process'
const curl = (...a) => JSON.parse(execFileSync('curl', ['-s', '--max-time', '60', ...a], { encoding: 'utf8' }))
fs.writeFileSync('/tmp/satsang-engine-worker/metadata.json', JSON.stringify({ main_module: 'worker.js', compatibility_date: '2026-10-01' }))
const up = curl('-X', 'PUT', `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/workers/scripts/${NAME}`,
  '-F', 'metadata=@/tmp/satsang-engine-worker/metadata.json;type=application/json',
  '-F', 'worker.js=@/tmp/satsang-engine-worker/worker.js;type=application/javascript+module')
console.log('upload', up.success, JSON.stringify(up.errors || []))
if (!up.success) process.exit(1)
const dom = curl('-X', 'PUT', `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/workers/domains`, '-H', 'content-type: application/json',
  '--data', JSON.stringify({ environment: 'production', hostname: HOST, service: NAME, zone_id: ZONE }))
console.log('domain', dom.success, JSON.stringify(dom.errors || []), dom.result?.hostname)
