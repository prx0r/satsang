// Deploy engine/ as a standalone preview Worker (satsang-engine-preview) on engine.tantrafiles.xyz.
// Touches nothing else: one new Worker script + one Worker custom domain (Cloudflare creates its own DNS record).
// Auth: the Hark gateway (or CLOUDFLARE_API_TOKEN) supplies the credential for api.cloudflare.com.
// usage: node tools/deploy-preview.mjs [--dry]
import fs from 'node:fs'
import path from 'node:path'
import url from 'node:url'
const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..')
const ACCOUNT = '954612afb5a97bb15dddcdc70176813d', ZONE = '4314ed02dc4c6f4cc1f6bf7638aa3a10'
const NAME = 'satsang-engine-preview', HOST = 'engine.tantrafiles.xyz'
const ls = (d, re) => fs.existsSync(path.join(ROOT, d)) ? fs.readdirSync(path.join(ROOT, d)).filter(f => re.test(f)).map(f => `${d}/${f}`) : []
const renders = fs.existsSync(path.join(ROOT, 'renders')) ? fs.readdirSync(path.join(ROOT, 'renders')) : []
const FILES = ['demo/index.html', 'compile.mjs', 'grammar.json', 'player/engine.js', 'player/player.js', 'player/player.css',
  ...ls('practices', /\.json$/), 'GRAMMAR.md', ...ls('schema', /\.json$/),
  ...fs.readdirSync(path.join(ROOT, 'pipeline')).flatMap(p => ls(`pipeline/${p}`, /^(instructions|narration|ask|timeline|build-report|head)\.json$/)),
  ...fs.readdirSync(path.join(ROOT, 'sources')).flatMap(p => ls(`sources/${p}`, /^source-text\.json$/)),
  ...renders.flatMap(r => [...ls(`renders/${r}/voice`, /\.(mp3|json)$/), ...ls(`renders/${r}/cues`, /\.(mp3|json)$/), ...ls(`renders/${r}/preview`, /^(preview-960x540\.mp4|poster-960\.jpg)$/)])]
const TYPES = { '.html': 'text/html; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.md': 'text/markdown; charset=utf-8', '.mp3': 'audio/mpeg', '.mp4': 'video/mp4', '.jpg': 'image/jpeg' }
const BIN = new Set(['.mp3', '.mp4', '.jpg'])
const text = FILES.filter(f => !BIN.has(path.extname(f))), bins = FILES.filter(f => BIN.has(path.extname(f)))
const assets = Object.fromEntries(text.map(f => ['/' + f, [TYPES[path.extname(f)], fs.readFileSync(path.join(ROOT, f), 'utf8')]]))
// binary files ride as Data modules (raw bytes, no base64), imported as ArrayBuffers; served with Range support (Safari video/audio)
const binMap = bins.map((f, i) => [`b${i}.bin`, '/' + f, TYPES[path.extname(f)]])
const worker = `// generated by engine/tools/deploy-preview.mjs: static preview of the Satsang practice engine
${binMap.map(([m], i) => `import B${i} from './${m}';`).join('\n')}
const A = ${JSON.stringify(assets)};
const BINS = { ${binMap.map(([, p, t], i) => `${JSON.stringify(p)}: [${JSON.stringify(t)}, B${i}]`).join(', ')} };
const H = { 'cache-control': 'public, max-age=300', 'x-robots-tag': 'noindex', 'x-content-type-options': 'nosniff', 'referrer-policy': 'strict-origin-when-cross-origin' };
export default { async fetch(req) {
  const u = new URL(req.url);
  let p = u.pathname;
  if (p === '/' || p === '/demo') return Response.redirect(u.origin + '/demo/' + u.search, 302);
  if (p.endsWith('/')) p += 'index.html';
  const b = BINS[p];
  if (b) {
    const buf = b[1], size = buf.byteLength, r = req.headers.get('range'), m = r && /bytes=(\\d*)-(\\d*)/.exec(r);
    if (m) { const s = m[1] ? +m[1] : size - +m[2], e = m[1] && m[2] ? Math.min(+m[2], size - 1) : size - 1;
      if (s >= size || s < 0) return new Response(null, { status: 416, headers: { 'content-range': 'bytes */' + size } });
      return new Response(buf.slice(s, e + 1), { status: 206, headers: { ...H, 'content-type': b[0], 'accept-ranges': 'bytes', 'content-range': 'bytes ' + s + '-' + e + '/' + size, 'content-length': String(e - s + 1) } }) }
    return new Response(buf, { headers: { ...H, 'content-type': b[0], 'accept-ranges': 'bytes', 'content-length': String(size) } });
  }
  const a = A[p];
  if (!a) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain' } });
  return new Response(a[1], { headers: { ...H, 'content-type': a[0] } });
} };
`
fs.mkdirSync('/tmp/satsang-engine-worker', { recursive: true })
fs.writeFileSync('/tmp/satsang-engine-worker/worker.js', worker)
for (const [m, p] of binMap) fs.copyFileSync(path.join(ROOT, p.slice(1)), '/tmp/satsang-engine-worker/' + m)
const binKB = binMap.reduce((t, [, p]) => t + fs.statSync(path.join(ROOT, p.slice(1))).size, 0) / 1024
console.log(`worker.js ${(worker.length / 1024).toFixed(1)} KB + ${binMap.length} binary modules ${binKB.toFixed(0)} KB, ${FILES.length} files`)
if (process.argv.includes('--dry')) process.exit(0)
// curl, not fetch: the credential gateway sits on curl's proxy path
import { execFileSync } from 'node:child_process'
const curl = (...a) => JSON.parse(execFileSync('curl', ['-s', '--max-time', '110', ...a], { encoding: 'utf8', maxBuffer: 1 << 26 }))
fs.writeFileSync('/tmp/satsang-engine-worker/metadata.json', JSON.stringify({ main_module: 'worker.js', compatibility_date: '2026-10-01' }))
const up = curl('-X', 'PUT', `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/workers/scripts/${NAME}`,
  '-F', 'metadata=@/tmp/satsang-engine-worker/metadata.json;type=application/json',
  '-F', 'worker.js=@/tmp/satsang-engine-worker/worker.js;type=application/javascript+module',
  ...binMap.flatMap(([m]) => ['-F', `${m}=@/tmp/satsang-engine-worker/${m};type=application/octet-stream`]))
console.log('upload', up.success, JSON.stringify(up.errors || []))
if (!up.success) process.exit(1)
const dom = curl('-X', 'PUT', `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT}/workers/domains`, '-H', 'content-type: application/json',
  '--data', JSON.stringify({ environment: 'production', hostname: HOST, service: NAME, zone_id: ZONE }))
console.log('domain', dom.success, JSON.stringify(dom.errors || []), dom.result?.hostname)
