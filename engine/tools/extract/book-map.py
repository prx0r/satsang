# Pass 1 for a sectioned book: merge the hand labels (labels.tsv, our words) with deterministic key terms counted in the
# private section texts, and write map.json + MAP.md (public: no source text).
# usage: python3 tools/extract/book-map.py <public source dir> <private dir>
import json, re, sys, collections

# canonical key term -> regex (case-insensitive). Only yoga vocabulary; counted per section, top 8 kept.
VOCAB = {
 'kundalini': r'kundalini|kundali', 'prana': r'\bprana\b', 'apana': r'\bapana\b', 'nadi': r'\bnadis?\b', 'ida': r'\bida\b',
 'pingala': r'\bpingala\b', 'sushumna': r'\bsushumna\b', 'chakra': r'\bchakras?\b', 'muladhara': r'muladhara', 'svadhishthana': r'svadhishthana',
 'manipura': r'manipura', 'anahata': r'\banahata\b', 'vishuddha': r'vi[s]?h?uddha', 'ajna': r'\bajna\b', 'sahasrara': r'sahasrara',
 'brahmarandhra': r'brahmarandhra', 'kanda': r'\bkanda\b', 'granthi': r'granthi', 'pranayama': r'pranayama', 'kumbhaka': r'kumbhaka',
 'puraka': r'\bpuraka\b', 'rechaka': r'\brechaka\b', 'om': r'\bom\b|\boms\b|pranava', 'bija': r'\bbija\b', 'japa': r'\bjapa\b',
 'mantra': r'\bmantras?\b', 'mula-bandha': r'mula\s?-?bandha', 'jalandhara-bandha': r'jalandhara', 'uddiyana-bandha': r'uddiyana',
 'maha-mudra': r'maha mudra', 'khechari': r'khechari|lambika', 'vajroli': r'vajroli', 'shakti-chalana': r'(?:s|sh)akti[- ]chalana',
 'yoni-mudra': r'yoni mudra', 'trataka': r'tratak', 'kapalabhati': r'kapalabhati', 'bhastrika': r'bhastrika', 'suryabheda': r'suryabheda',
 'ujjayi': r'ujjayi', 'sitali': r'sitali', 'nauli': r'\bnauli\b', 'dhauti': r'dhauti', 'basti': r'\bbasti\b', 'neti': r'\bneti\b',
 'padmasana': r'padmasana|padma asana', 'siddhasana': r'siddhasana|siddha asana', 'sirshasana': r'sirshasana', 'asana': r'\basanas?\b',
 'guru': r'\bguru', 'brahmacharya': r'brahmachar', 'mitahara': r'mitahara', 'diet': r'\bdiet\b|\bfood\b', 'siddhi': r'siddhis?\b',
 'samadhi': r'samadhi', 'concentration': r'dharana|concentrat', 'nada': r'\bnada\b|anahata sound', 'vairagya': r'vairagya', 'mouna': r'mouna|mowna',
 'shiva': r'\bs[h]?iva\b', 'shakti': r'\bs[h]?akti\b', 'tattva': r'tattva', 'kevala': r'\bkevala\b', 'sahita': r'\bsahita\b',
}
VOCAB = {k: re.compile(v, re.I) for k, v in VOCAB.items()}
LABELS = {'practice', 'theory', 'teacher-only', 'rules', 'story', 'front-matter'}
TIERS = {'beginner-ok', 'needs-review', 'teacher-only'}

def main():
    pub, priv = sys.argv[1:3]
    S = json.load(open(f'{pub}/sections.json')); idx = json.load(open(f'{pub}/passage-index.json'))
    first, last, count = {}, {}, collections.Counter()
    for r in idx['rows']:
        seg = r[0].split(':')[0]; first.setdefault(seg, r[0]); last[seg] = r[0]; count[seg] += 1
    lab = {}
    for line in open(f'{pub}/labels.tsv', encoding='utf-8'):
        if line.startswith('#') or not line.strip(): continue
        n, label, tier, run, cand, para = line.rstrip('\n').split('|', 5)
        assert label in LABELS and tier in TIERS and run in '01', line
        lab[int(n)] = dict(label=label, tier=tier, runnable_candidate=run == '1', candidate=None if cand == '-' else cand, paraphrase=para)
    assert set(lab) == {s['ordinal'] for s in S['sections']}, 'labels must cover every section exactly once'
    out = []
    for s in S['sections']:
        t = open(f'{priv}/{s["file"]}', encoding='utf-8').read()
        c = collections.Counter({k: len(rx.findall(t)) for k, rx in VOCAB.items()})
        terms = [k for k, v in sorted(c.items(), key=lambda kv: (-kv[1], kv[0])) if v][:8]
        L = lab[s['ordinal']]
        out.append({'id': s['id'], 'heading': s['heading'], 'part': s['part'], 'words': s['words'], **L, 'key_terms': terms,
                    'passages': {'first': first.get(s['id']), 'last': last.get(s['id']), 'count': count[s['id']]}})
    by = collections.Counter(x['label'] for x in out); bt = collections.Counter(x['tier'] for x in out)
    res = {'type': 'book_map', 'schema_version': 1, 'source': S['source'], 'pass': 1, 'labelled_by': 'agent draft 2026-10-26 (status: review)',
           'counts': {'label': dict(by), 'tier': dict(bt), 'runnable_candidates': sum(x['runnable_candidate'] for x in out)}, 'sections': out}
    json.dump(res, open(f'{pub}/map.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1); open(f'{pub}/map.json', 'a').write('\n')
    # MAP.md
    md = ['# Sivananda, *Kundalini Yoga*: section map (pass 1)', '',
          'Generated by `engine/tools/extract/book-map.py` from `labels.tsv` (hand labels, our words) + key terms counted in the private texts. '
          'No source text here; paraphrases are ours. Status: **review** (agent draft, not signed off).', '',
          '**Labels:** ' + ', '.join(f'{k} {v}' for k, v in by.most_common()) + '  ',
          '**Tiers:** ' + ', '.join(f'{k} {v}' for k, v in bt.most_common()) + '  ',
          f'**Runnable candidates:** {res["counts"]["runnable_candidates"]} (★)', '']
    part = None
    for x in out:
        if x['part'] != part:
            part = x['part']; pl = next(p['label'] for p in S['parts'] if p['id'] == part)
            md += ['', f'## {pl}', '', '| id | heading | label | tier | ★ | words | key terms | paraphrase |', '|---|---|---|---|---|---|---|---|']
        md.append(f"| `{x['id']}` | {x['heading']} | {x['label']} | {x['tier']} | {'★ ' + x['candidate'] if x['runnable_candidate'] else ''} | {x['words']} | {', '.join(x['key_terms'][:5])} | {x['paraphrase'].replace('|', '/')} |")
    open(f'{pub}/MAP.md', 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print(dict(by), dict(bt), res['counts']['runnable_candidates'])

if __name__ == '__main__':
    main()
